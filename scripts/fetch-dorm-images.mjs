#!/usr/bin/env node
/**
 * Fetches hero images from provider dorm pages and writes dorm_images.sql.
 * Run: node scripts/fetch-dorm-images.mjs
 */
import fs from 'fs'
import path from 'path'

const ROOT = process.cwd()
const SEED_FILES = [
  'supabase/seeds/oead_vienna.sql',
  'supabase/seeds/stuwo_vienna.sql',
  'supabase/seeds/home4students_vienna.sql',
]

const BOT = 'Dormra-Bot/1.0 (+https://dormra.eu)'
const DELAY_MS = 400

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms))
}

function parseDormsFromSeed(filePath) {
  const text = fs.readFileSync(path.join(ROOT, filePath), 'utf8')
  const rows = []
  const re = /\('([^']+)',\s*'([^']+)'[\s\S]*?'(https?:\/\/[^']+)',\s*'(?:playwright|cheerio)'/g
  let match
  while ((match = re.exec(text)) !== null) {
    rows.push({ slug: match[1], provider: match[2], scrapeUrl: match[3] })
  }
  return rows
}

function extractImage(html, provider) {
  const og = html.match(/property="og:image"\s+content="([^"]+)"/i)
    ?? html.match(/content="([^"]+)"\s+property="og:image"/i)

  if (provider === 'STUWO' && og?.[1] && !og[1].includes('Logo')) {
    return og[1]
  }

  if (provider === 'OeAD') {
    const hero = html.match(
      /https:\/\/oeadstudenthousing-public-production\.s3\.amazonaws\.com\/images\/[^"'\\]+\.fill-1580x240\.jpg/i,
    )
    if (hero) return hero[0]

    const gallery = html.match(
      /https:\/\/oeadstudenthousing-public-production\.s3\.amazonaws\.com\/images\/[^"'\\]+\.max-(?:1860x969|1920x1080)\.jpg/i,
    )
    if (gallery) return gallery[0]
  }

  if (og?.[1] && !og[1].includes('favicon') && !og[1].includes('Logo')) {
    return og[1]
  }

  return null
}

async function fetchH4SImages() {
  const res = await fetch('https://www.home4students.at/en/our-dormitories/dormitories-vienna/', {
    headers: { 'User-Agent': BOT },
  })
  const html = await res.text()
  const images = [...html.matchAll(
    /background-image:url\((https:\/\/www\.home4students\.at\/wp-content\/uploads\/[^)]+)\)/g,
  )].map((m) => m[1])

  // First image is page hero — remaining map 1:1 to Vienna dorm order on the page.
  const slugs = [
    'h4s-grosse-schiffgasse',
    'h4s-schaeffergasse',
    'h4s-neudeggergasse',
    'h4s-boltzmanngasse',
    'h4s-hofergasse',
    'h4s-sensengasse',
    'h4s-erlachplatz',
    'h4s-ullmannstrasse',
    'h4s-doebling-front',
    'h4s-doebling-back',
    'h4s-popup-seestadt',
  ]

  const map = {}
  slugs.forEach((slug, index) => {
    const url = images[index + 1]
    if (url) map[slug] = url
  })
  return map
}

async function main() {
  const dorms = SEED_FILES.flatMap((file) => parseDormsFromSeed(file))
  const h4sImages = await fetchH4SImages()
  const results = []

  for (const dorm of dorms) {
    await sleep(DELAY_MS)
    let imageUrl = h4sImages[dorm.slug] ?? null

    if (!imageUrl) {
      try {
        const res = await fetch(dorm.scrapeUrl, {
          headers: { 'User-Agent': BOT, 'Accept-Language': 'en,de;q=0.8' },
        })
        if (res.ok) {
          const html = await res.text()
          imageUrl = extractImage(html, dorm.provider)
        }
      } catch (err) {
        console.warn(`Failed ${dorm.slug}:`, err.message)
      }
    }

    results.push({ ...dorm, imageUrl })
    console.log(`${dorm.slug}: ${imageUrl ?? 'MISSING'}`)
  }

  const lines = [
    '-- ============================================================================',
    '-- Seed: dorm hero images (generated by scripts/fetch-dorm-images.mjs)',
    '-- APPLY: psql $DATABASE_URL -f supabase/seeds/dorm_images.sql',
    '-- Idempotent: upserts image_url on slug.',
    '-- ============================================================================',
    '',
    ...results
      .filter((r) => r.imageUrl)
      .map(
        (r) =>
          `update public.dorms set image_url = '${r.imageUrl.replace(/'/g, "''")}' where slug = '${r.slug}';`,
      ),
    '',
  ]

  const outPath = path.join(ROOT, 'supabase/seeds/dorm_images.sql')
  fs.writeFileSync(outPath, lines.join('\n'))
  console.log(`\nWrote ${results.filter((r) => r.imageUrl).length}/${results.length} images to ${outPath}`)
}

main()
