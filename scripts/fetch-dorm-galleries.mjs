#!/usr/bin/env node
/**
 * Fetches multi-photo galleries for OeAD dorms (their pages expose a clean
 * JSON-in-HTML gallery with per-image titles, unlike STUWO/home4students
 * whose markup makes reliably grouping "this dorm's gallery" vs. reused
 * template assets much harder). Reuses the same extraction + scoring
 * approach as fetch-dorm-images.mjs (single hero image), but keeps the
 * top N candidates per dorm instead of just the best one.
 *
 * Writes supabase/seeds/dorm_image_galleries.sql — additive to the existing
 * single-image dorm_images.sql seed (dorms.image_url), not a replacement.
 *
 * Run: node scripts/fetch-dorm-galleries.mjs
 */
import fs from 'fs'
import path from 'path'

const ROOT = process.cwd()
const BOT = 'Dormra-Bot/1.0 (+https://dormra.eu)'
const DELAY_MS = 350
const MAX_IMAGES_PER_DORM = 5

function parseOeadDorms(filePath) {
  const text = fs.readFileSync(path.join(ROOT, filePath), 'utf8')
  const rows = []
  const re = /\('([^']+)',\s*'OeAD'[\s\S]*?'(https?:\/\/[^']+)',\s*'playwright'/g
  let match
  while ((match = re.exec(text)) !== null) {
    rows.push({ slug: match[1], scrapeUrl: match[2] })
  }
  return rows
}

function decodeUrl(url) {
  try {
    return decodeURIComponent(url)
  } catch {
    return url
  }
}

function extractOeadGalleryItems(html) {
  const items = []
  const re =
    /\{&quot;title&quot;:&quot;([^&]+)&quot;,&quot;src&quot;:&quot;(https:\/\/oeadstudenthousing-public-production\.s3\.amazonaws\.com\/images\/[^&]+)&quot;/g
  let match
  while ((match = re.exec(html)) !== null) {
    items.push({ title: match[1].replace(/&amp;/g, '&'), url: match[2] })
  }
  return items
}

function scoreOeadItem({ title, url }) {
  const name = decodeUrl(url.split('/').pop() ?? '').toLowerCase()
  const t = title.toLowerCase()

  if (name.includes('fill-1580x240') || name.includes('fill-472') || name.includes('istock')) {
    return -100
  }
  if (/zimmertyp|_kat|kat[a-z]?_|grundriss|virtual|floorplan|icon|logo|max-900x90|zi\d|zimmer/.test(name)) {
    return -100
  }
  if (!name.includes('max-1920x1080')) return -50

  let score = 10

  const isBuildingCarousel =
    /^oead-(guesthouse|apartment)\s/.test(t) &&
    !/\sgallery\s*(kitchen|bathroom|gym|sauna|hallway|couch|mailbox|elevator|terrace|bad|kueche|fitness|zimmer|musik|kletter|wasch|arbeitsfl|allgemein|greenhouse|gang|sofa|lift|briefkasten|essecke)/.test(
      t,
    ) &&
    !/\sgallery$/.test(t.trim())

  if (isBuildingCarousel) score += 65

  if (/aussen|außen|eingang|entrance|facade|fassade|terrasse|terrace|ansicht|outside|building/.test(`${name} ${t}`)) {
    score += 45
  }
  if (/gallery-aussen|gallery_eingang|gallery-eingang|_aussen|_header/.test(name)) score += 45

  if (
    /gallery kitchen|gallery bathroom|gallery gym|gallery sauna|gallery hallway|gallery couch|gallery mailbox|gallery elevator|gallery bad|gallery kueche|gallery fitness|gallery zimmer|musikzimmer|kletterraum|waschk|arbeitsfl|allgemein|gallery gang|gallery sofa|gallery lift|essecke/.test(
      t,
    )
  ) {
    score -= 55
  }
  if (/kueche|kitchen|bad|bath|gym|sauna|fitness|zimmer|musik|kletter|wasch|arbeitsfl|allgemein|gang|sofa|lift|briefkasten|essecke|arbeitsfl/.test(name)) {
    score -= 45
  }

  if (/gallery1\.max-1920/.test(name) && isBuildingCarousel) score += 8

  return score
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms))
}

async function fetchPage(url) {
  const res = await fetch(url, { headers: { 'User-Agent': BOT, 'Accept-Language': 'en,de;q=0.8' } })
  if (!res.ok) return null
  return res.text()
}

async function main() {
  const dorms = parseOeadDorms('supabase/seeds/oead_vienna.sql')
  const results = []

  for (const dorm of dorms) {
    await sleep(DELAY_MS)
    let images = []

    try {
      const html = await fetchPage(dorm.scrapeUrl)
      if (html) {
        const items = extractOeadGalleryItems(html)
        const ranked = items
          .map((item) => ({ ...item, score: scoreOeadItem(item) }))
          .filter((r) => r.score > 0)
          .sort((a, b) => b.score - a.score)

        const seen = new Set()
        for (const r of ranked) {
          if (seen.has(r.url)) continue
          seen.add(r.url)
          images.push(r.url)
          if (images.length >= MAX_IMAGES_PER_DORM) break
        }
      }
    } catch (err) {
      console.warn(`Failed ${dorm.slug}:`, err.message)
    }

    results.push({ ...dorm, images })
    console.log(`${images.length > 0 ? 'OK  ' : 'NONE'} ${dorm.slug}: ${images.length} images`)
  }

  const lines = [
    '-- ============================================================================',
    '-- Seed: OeAD dorm photo galleries (generated by scripts/fetch-dorm-galleries.mjs)',
    '-- Additive to dorm_images.sql (dorms.image_url single hero) — populates the',
    '-- dorm_images table used by the detail-page gallery carousel.',
    '-- APPLY: psql $DATABASE_URL -f supabase/seeds/dorm_image_galleries.sql',
    '-- Idempotent: ON CONFLICT (dorm_id, url) DO NOTHING.',
    '-- ============================================================================',
    '',
  ]

  for (const r of results) {
    if (r.images.length === 0) continue
    lines.push(`-- ${r.slug} (${r.images.length} photos)`)
    r.images.forEach((url, i) => {
      lines.push(
        `insert into public.dorm_images (dorm_id, url, sort_order)\n` +
          `  select id, '${url.replace(/'/g, "''")}', ${i} from public.dorms where slug = '${r.slug}'\n` +
          `  on conflict (dorm_id, url) do nothing;`,
      )
    })
    lines.push('')
  }

  const outPath = path.join(ROOT, 'supabase/seeds/dorm_image_galleries.sql')
  fs.writeFileSync(outPath, lines.join('\n'))
  const ok = results.filter((r) => r.images.length > 0).length
  const totalImages = results.reduce((sum, r) => sum + r.images.length, 0)
  console.log(`\nWrote ${ok}/${results.length} dorms with galleries (${totalImages} images total) to ${outPath}`)
}

main()
